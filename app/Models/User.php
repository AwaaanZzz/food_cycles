<?php

namespace App\Models;

use Database\Factories\UserFactory;
use Illuminate\Contracts\Auth\MustVerifyEmail;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;

class User extends Authenticatable implements MustVerifyEmail
{
    /** @use HasFactory<UserFactory> */
    use HasFactory, Notifiable;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'dietary_preferences',
        'available_tools',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var list<string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'dietary_preferences' => 'array',
            'available_tools' => 'array',
        ];
    }

    /**
     * Get all recipes generated by the user.
     */
    public function recipes(): HasMany
    {
        return $this->hasMany(Recipe::class)->latest();
    }

    /**
     * Get saved / favorited recipes.
     */
    public function savedRecipes(): HasMany
    {
        return $this->hasMany(Recipe::class)->where('is_saved', true)->latest();
    }

    /**
     * Items in the user's fridge / pantry, soonest expiry first.
     */
    public function pantryItems(): HasMany
    {
        return $this->hasMany(PantryItem::class)->orderByRaw('expires_at IS NULL')->orderBy('expires_at');
    }

    /**
     * Weekly meal plans generated for the user.
     */
    public function mealPlans(): HasMany
    {
        return $this->hasMany(MealPlan::class)->latest();
    }

    /**
     * Check if user has a dietary preference.
     */
    public function hasDietaryPreference(string $pref): bool
    {
        return in_array($pref, $this->dietary_preferences ?? []);
    }

    /**
     * Check if user has a cooking tool.
     */
    public function hasCookingTool(string $tool): bool
    {
        return in_array($tool, $this->available_tools ?? []);
    }
}
