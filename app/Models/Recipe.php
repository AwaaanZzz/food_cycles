<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class Recipe extends Model
{
    use HasFactory;

    protected $fillable = [
        'user_id',
        'title',
        'description',
        'type',
        'cooking_time',
        'servings',
        'difficulty',
        'estimated_cost',
        'ingredients',
        'cooking_tools',
        'steps',
        'nutrition',
        'tips',
        'image_path',
        'source_input',
        'is_saved',
        'share_token',
        'rating',
        'user_notes',
    ];

    protected $casts = [
        'ingredients' => 'array',
        'cooking_tools' => 'array',
        'steps' => 'array',
        'nutrition' => 'array',
        'source_input' => 'array',
        'is_saved' => 'boolean',
        'estimated_cost' => 'integer',
    ];

    /**
     * The user that generated this recipe.
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Scope for saved / favorited recipes.
     */
    public function scopeSaved(Builder $query): Builder
    {
        return $query->where('is_saved', true);
    }

    /**
     * Scope filter by feature type.
     */
    public function scopeByType(Builder $query, ?string $type): Builder
    {
        if ($type) {
            return $query->where('type', $type);
        }
        return $query;
    }

    /**
     * URL for the recipe image, served through the auth-protected media route
     * so only the recipe owner can view it.
     */
    public function getImageUrlAttribute(): ?string
    {
        if (!$this->image_path) {
            return null;
        }
        return url('/recipe-media/' . $this->image_path);
    }

    /**
     * Fallback URL for recipe image if symlink is inaccessible.
     */
    public function getFallbackImageUrlAttribute(): ?string
    {
        if (!$this->image_path) {
            return null;
        }
        return url('/recipe-media/' . $this->image_path);
    }

    /**
     * Formatted Indonesian Rupiah cost.
     */
    public function getFormattedCostAttribute(): string
    {
        return 'Rp ' . number_format($this->estimated_cost ?? 0, 0, ',', '.');
    }

    /**
     * Alias for estimated_cost_idr
     */
    public function getEstimatedCostIdrAttribute(): int
    {
        return (int) ($this->estimated_cost ?? 0);
    }

    /**
     * Alias for cooking_time_minutes
     */
    public function getCookingTimeMinutesAttribute(): ?string
    {
        return $this->cooking_time;
    }

    /**
     * Alias for tools
     */
    public function getToolsAttribute(): ?array
    {
        return $this->cooking_tools;
    }

    /**
     * Alias for nutrition_info
     */
    public function getNutritionInfoAttribute(): ?array
    {
        return $this->nutrition;
    }

    /**
     * Official disclaimer
     */
    public function getDisclaimerAttribute(): string
    {
        return 'Catatan: Informasi estimasi harga bahan makanan (IDR) dan kandungan gizi dihitung oleh kecerdasan buatan (AI) sebagai perkiraan rata-rata dan dapat berbeda tergantung lokasi pasar, waktu, serta penyedia bahan.';
    }


    /**
     * Whether recipe was generated by live Gemini AI.
     */
    public function getIsLiveAiAttribute(): bool
    {
        return (bool) ($this->source_input['is_ai_generated'] ?? true);
    }

    /**
     * Name of the AI model used.
     */
    public function getAiModelNameAttribute(): string
    {
        return (string) ($this->source_input['ai_model'] ?? 'gemini-3.5-flash-lite');
    }

    /**
     * Error notice if fallback was triggered.
     */
    public function getErrorNoticeAttribute(): ?string
    {
        return $this->source_input['error_notice'] ?? null;
    }

    /**
     * Label for the feature type.
     */
    public function getTypeLabelAttribute(): string
    {
        return match ($this->type) {
            'fcai' => 'Bahan & Peralatan',
            'fcbb' => 'Sesuai Anggaran',
            'fbpb' => 'Dari Foto',
            default => strtoupper($this->type),
        };
    }

    /**
     * Badge styles according to feature type.
     */
    public function getTypeBadgeClassesAttribute(): string
    {
        return match ($this->type) {
            'fcai' => 'bg-emerald-50 text-emerald-800 border-emerald-200',
            'fcbb' => 'bg-amber-50 text-amber-800 border-amber-200',
            'fbpb' => 'bg-blue-50 text-blue-800 border-blue-200',
            default => 'bg-slate-100 text-slate-700 border-slate-200',
        };
    }
}
